"""Train a tiny GPT style language model on a generated text corpus in native Truestar, next to the
same model written with torch.nn, then generate from it with a KV cache.

    python examples/nn_gpt.py            # float64 loss curves and generation, about 20 s
    python examples/nn_gpt.py --bench    # also float32: compiled CPU (and CUDA) vs eager

The corpus is generated by a small grammar ("the cat sees a red fox. a dog likes the big hen. ..."),
character level, 27 symbols. The model: token and position embeddings, 2 pre norm transformer
blocks (causal multi head attention, GELU MLP), a final layer norm and an untied head; AdamW with
warmup and cosine decay, clipping at 1.0. The PyTorch side is a hand written torch.nn model with
the same structure and weights. Prints the worst relative difference of the loss curves (float64,
bar 1e-9), then greedy generation through the KV cache, checked against full recomputation.
"""

import argparse
import math
import statistics
import time

import torch

import truestar
from truestar import Tensor, nn, ops, optim

VOCAB = " abcdefghijklmnopqrstuvwxyz."
V, CTX, DIM, HEADS, DEPTH, B = len(VOCAB), 32, 48, 4, 2, 16


@nn.layer
class GPT(nn.Layer):
    vocab: int
    dim: int
    heads: int
    depth: int
    ctx: int
    dtype: str = "f32"

    def children(self):
        out = {"tok": nn.Embedding(self.vocab, self.dim, std=0.02, dtype=self.dtype),
               "pos": nn.Embedding(self.ctx, self.dim, std=0.02, dtype=self.dtype)}
        for i in range(self.depth):
            out[f"b{i}"] = nn.TransformerBlock(self.dim, self.heads, dtype=self.dtype)
        out["norm"] = nn.LayerNorm(self.dim, dtype=self.dtype)
        out["head"] = nn.Linear(self.dim, self.vocab, bias=False, dtype=self.dtype)
        return out

    def forward(self, p, ids, pos, cache=None):
        x = self.tok(p["tok"], ids) + self.pos(p["pos"], pos)
        new = ()
        for i in range(self.depth):
            k = "b" + str(i)
            if cache is None:
                x = self.parts[k](p[k], x)
            else:
                x, c = self.parts[k](p[k], x, cache=cache[k], pos=pos)
                new = new + (c,)
        logits = self.head(p["head"], self.norm(p["norm"], x))
        if cache is None:
            return logits
        return logits, dict(zip(cache.keys(), new))

    def init_cache(self, batch, capacity):
        return {f"b{i}": self.parts[f"b{i}"].attn.init_cache(batch, capacity) for i in range(self.depth)}

    def cache_spec(self):
        return {f"b{i}": self.parts[f"b{i}"].attn.cache_spec() for i in range(self.depth)}


def make_fns(m, dt):
    @truestar.native
    def loss(p: m.spec, ids: Tensor["B", "T", "i64"], pos: Tensor["T", "i64"], tgt: Tensor["B", "T", "i64"]) -> Tensor[dt]:
        return nn.cross_entropy(m(p, ids, pos), tgt)

    @truestar.native
    def decode(p: m.spec, ids: Tensor["B", "T", "i64"], pos: Tensor["T", "i64"], cache: m.cache_spec()):
        logits, c2 = m(p, ids, pos, cache)
        nxt = ops.argmax(logits[:, ids.shape[1] - 1], dim=-1)   # greedy pick inside the program
        return logits, nxt, c2
    return loss, decode


def corpus(n_chars, seed=0):
    g = torch.Generator().manual_seed(seed)
    words = {"det": ["the", "a"], "adj": ["red", "big", "old", "small", ""], "noun": ["cat", "dog", "fox", "hen", "owl"],
             "verb": ["sees", "likes", "chases", "finds"]}

    def pick(k):
        w = words[k]
        return w[int(torch.randint(0, len(w), (1,), generator=g))]

    out = []
    while sum(len(s) for s in out) < n_chars:
        a, b = pick("adj"), pick("adj")
        out.append(f"{pick('det')} {a + ' ' if a else ''}{pick('noun')} {pick('verb')} {pick('det')} "
                   f"{b + ' ' if b else ''}{pick('noun')}. ")
    text = "".join(out)[:n_chars]
    return torch.tensor([VOCAB.index(c) for c in text])


def batches(n, seed=0):
    data = corpus(20000, seed)
    g = torch.Generator().manual_seed(seed + 1)
    starts = torch.randint(0, len(data) - CTX - 1, (n, B), generator=g)
    xs = torch.stack([torch.stack([data[s:s + CTX] for s in row]) for row in starts])
    ys = torch.stack([torch.stack([data[s + 1:s + CTX + 1] for s in row]) for row in starts])
    return xs, ys


class TorchBlock(torch.nn.Module):
    def __init__(self):
        super().__init__()
        self.n1, self.n2 = torch.nn.LayerNorm(DIM), torch.nn.LayerNorm(DIM)
        self.q, self.k, self.v, self.o = (torch.nn.Linear(DIM, DIM) for _ in range(4))
        self.fc1, self.fc2 = torch.nn.Linear(DIM, 4 * DIM), torch.nn.Linear(4 * DIM, DIM)

    def forward(self, x):
        b, t, _ = x.shape
        h = self.n1(x)
        q, k, v = (f(h).view(b, t, HEADS, DIM // HEADS).transpose(1, 2) for f in (self.q, self.k, self.v))
        a = torch.nn.functional.scaled_dot_product_attention(q, k, v, is_causal=True)
        x = x + self.o(a.transpose(1, 2).reshape(b, t, DIM))
        return x + self.fc2(torch.nn.functional.gelu(self.fc1(self.n2(x))))


class TorchGPT(torch.nn.Module):
    def __init__(self):
        super().__init__()
        self.tok, self.pos = torch.nn.Embedding(V, DIM), torch.nn.Embedding(CTX, DIM)
        self.blocks = torch.nn.ModuleList(TorchBlock() for _ in range(DEPTH))
        self.norm, self.head = torch.nn.LayerNorm(DIM), torch.nn.Linear(DIM, V, bias=False)

    def forward(self, ids):
        x = self.tok(ids) + self.pos(torch.arange(ids.shape[1], device=ids.device))
        for blk in self.blocks:
            x = blk(x)
        return self.head(self.norm(x))


def torch_model(p, dtype):
    m = TorchGPT().to(dtype)
    with torch.no_grad():
        m.tok.weight.copy_(p["tok"]["w"])
        m.pos.weight.copy_(p["pos"]["w"])
        m.head.weight.copy_(p["head"]["w"])
        m.norm.weight.copy_(p["norm"]["w"])
        m.norm.bias.copy_(p["norm"]["b"])
        for i, blk in enumerate(m.blocks):
            q = p[f"b{i}"]
            for name in ("n1", "n2"):
                getattr(blk, name).weight.copy_(q[name]["w"])
                getattr(blk, name).bias.copy_(q[name]["b"])
            for name in ("q", "k", "v", "o"):
                getattr(blk, name).weight.copy_(q["attn"][name]["w"])
                getattr(blk, name).bias.copy_(q["attn"][name]["b"])
            for name in ("fc1", "fc2"):
                getattr(blk, name).weight.copy_(q["mlp"][name]["w"])
                getattr(blk, name).bias.copy_(q["mlp"][name]["b"])
    return m


def run_torch(p, opt, xs, ys, steps, dtype, device="cpu"):
    m = torch_model(p, dtype).to(device)
    to = torch.optim.AdamW(m.parameters(), lr=1.0, weight_decay=opt.weight_decay)
    sched = torch.optim.lr_scheduler.LambdaLR(to, lambda i: opt.lr_at(i))
    losses, times = [], []
    for i in range(steps):
        t0 = time.perf_counter()
        x, y = xs[i].to(device), ys[i].to(device)
        to.zero_grad()
        loss = torch.nn.functional.cross_entropy(m(x).reshape(-1, V), y.reshape(-1))
        loss.backward()
        torch.nn.utils.clip_grad_norm_(m.parameters(), 1.0)
        to.step()
        sched.step()
        losses.append(loss.item())
        times.append(time.perf_counter() - t0)
    return losses, statistics.median(times[3:])


def run_truestar(step, p, xs, ys, steps, device="cpu"):
    ts = step.init(_to(p, device))
    pos = torch.arange(CTX, device=device)
    losses, times = [], []
    for i in range(steps):
        t0 = time.perf_counter()
        ts, r = step(ts, xs[i].to(device), pos, ys[i].to(device))
        losses.append(r.loss)
        times.append(time.perf_counter() - t0)
    return losses, statistics.median(times[3:]), ts


def _to(tree, device=None, dtype=None):
    if isinstance(tree, dict):
        return {k: _to(v, device, dtype) for k, v in tree.items()}
    return tree.to(device=device, dtype=dtype if tree.dtype.is_floating_point and dtype else tree.dtype)


def worst_rel(a, b):
    return max(abs(x - y) / abs(y) for x, y in zip(a, b))


def generate(m, decode, p, prompt, n, dtype):
    """Greedy generation through the KV cache: one compiled program for the prompt and every step."""
    ids = torch.tensor([[VOCAB.index(c) for c in prompt]])
    cache = m.init_cache(1, CTX)
    logits, nxt, cache = decode(p, ids, torch.arange(ids.shape[1]), cache)
    out = [int(nxt)]
    for t in range(ids.shape[1], ids.shape[1] + n - 1):
        cache = _to(cache, dtype=dtype)
        logits, nxt, cache = decode(p, nxt.reshape(1, 1), torch.tensor([t]), cache)
        out.append(int(nxt))
    full = torch.cat([ids, torch.tensor([out[:-1]])], 1)
    return "".join(VOCAB[i] for i in out), full


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--steps", type=int, default=40)
    ap.add_argument("--bench", action="store_true")
    args = ap.parse_args()
    steps = args.steps
    opt = optim.AdamW(lr=optim.warmup_cosine(3e-3, max(steps // 10, 1), steps), weight_decay=0.01)
    xs, ys = batches(steps)

    m = GPT(V, DIM, HEADS, DEPTH, CTX, "f64")
    loss, decode = make_fns(m, "f64")
    p = m.init(seed=0)
    step = truestar.train_step(loss, opt, clip=1.0)
    ours, _, ts = run_truestar(step, p, xs, ys, steps)
    ref, _ = run_torch(p, opt, xs, ys, steps, torch.float64)
    print(f"float64 ({steps} steps): loss {ours[0]:.4f} -> {ours[-1]:.4f} (uniform guess {math.log(V):.4f}); "
          f"worst relative difference to PyTorch {worst_rel(ours, ref):.2e} (bar 1e-9)")
    print(f"step program: {len(step.program.nodes)} IR nodes, {m.num_params()} params")
    text, full = generate(m, decode, ts.params, "the cat ", 16, torch.float64)
    again = m(_to(ts.params), full, torch.arange(full.shape[1]))
    greedy = again[0, 7:].argmax(-1)
    same = "".join(VOCAB[int(i)] for i in greedy) == text
    print(f"generated: 'the cat {text}' ({decode.compile_count} compile for prompt and {len(text) - 1} decode "
          f"steps; equals full recomputation: {same})")

    if args.bench:
        m32 = GPT(V, DIM, HEADS, DEPTH, CTX, "f32")
        loss32, _ = make_fns(m32, "f32")
        p32 = m32.init(seed=0)
        for dev in ["cpu"] + (["cuda"] if torch.cuda.is_available() else []):
            t0 = time.perf_counter()
            st = truestar.train_step(loss32, opt, clip=1.0, executor=dev)
            ours32, t_ours, _ = run_truestar(st, p32, xs, ys, steps, dev)
            first = time.perf_counter() - t0
            ref32, t_ref = run_torch(p32, opt, xs, ys, steps, torch.float32, dev)
            print(f"float32 {dev}: worst relative loss difference {worst_rel(ours32, ref32):.2e}; per step "
                  f"Truestar compiled {t_ours * 1e3:.2f} ms, PyTorch eager {t_ref * 1e3:.2f} ms "
                  f"(PyTorch / Truestar {t_ref / t_ours:.2f}); whole run with compile and first call check "
                  f"{first:.1f} s; median of steps 4 on, preliminary (noisy shared machine)")


if __name__ == "__main__":
    main()
