"""Write proofs/lean/TruestarProofs/Constants.lean from the constants of src/truestar/kernel/tcexact.py.

The Lean proofs (proofs/lean/TruestarProofs/Instances.lean) are instantiated at these constants and
check their side conditions with `decide`, so a weakened constant (a narrower tensor core window,
another accumulator start, a larger K block or wider digits) makes `lake build` fail.

The constants are read with `ast` (no import of truestar, no torch). Usage:

    python scripts/gen_lean_constants.py            # write the file
    python scripts/gen_lean_constants.py --check    # exit 1 if the file is out of date
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "truestar" / "kernel" / "tcexact.py"
OUT = ROOT / "proofs" / "lean" / "TruestarProofs" / "Constants.lean"

# (Python name, Lean name, Lean type, meaning)
CONSTANTS = (
    ("TC_FRAC_BITS_MIN", "TC_FRAC_BITS_MIN", "Nat", "narrowest alignment window accepted (fraction bits)"),
    ("_RN", "ACC_START", "Int", "fp16 engine accumulator start C = 1.5 * 2**23"),
    ("TOP_MAX", "TOP_MAX", "Nat", "|d0| <= TOP_MAX"),
    ("LOW_MAX", "LOW_MAX", "Nat", "|d1|, |d2| <= LOW_MAX"),
    ("DIGIT_BITS", "DIGIT_BITS", "Nat", "digit weight 2**-DIGIT_BITS"),
    ("DIGITS", "DIGITS", "Nat", "digits per operand value"),
    ("SUM_BITS", "SUM_BITS", "Nat", "every |I_w| is below 2**SUM_BITS"),
    ("PORTABLE_BK", "PORTABLE_BK", "Nat", "K block of the portable mode"),
    ("MAX_KB", "MAX_KB", "Nat", "largest K block of one exact block"),
)


def read_constants(path: Path = SRC) -> dict:
    """Module level integer constants of tcexact.py (floats must be whole numbers)."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    found = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            names = [target] if isinstance(target, ast.Name) else (
                list(target.elts) if isinstance(target, ast.Tuple) else [])
            try:
                value = ast.literal_eval(node.value)
            except ValueError:
                continue
            values = [value] if isinstance(target, ast.Name) else list(value)
            for n, v in zip(names, values):
                if isinstance(n, ast.Name) and isinstance(v, (int, float)) and not isinstance(v, bool):
                    found[n.id] = v
    out = {}
    for py, lean, _, _ in CONSTANTS:
        if py not in found:
            raise SystemExit(f"{py} not found as a literal in {path}")
        v = found[py]
        if float(v) != int(v):
            raise SystemExit(f"{py} = {v} is not a whole number")
        out[lean] = int(v)
    return out


def render(values: dict) -> str:
    lines = [
        "-- Generated by scripts/gen_lean_constants.py from src/truestar/kernel/tcexact.py.",
        "-- Do not edit by hand: rerun the script (tests/test_lean_constants.py checks it is current).",
        "namespace Truestar.Const",
        "",
    ]
    for _, lean, typ, meaning in CONSTANTS:
        lines.append(f"/-- {meaning} -/")
        lines.append(f"def {lean} : {typ} := {values[lean]}")
    lines += ["", "end Truestar.Const", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the Lean file is out of date")
    args = ap.parse_args(argv)
    text = render(read_constants())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date: run scripts/gen_lean_constants.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
