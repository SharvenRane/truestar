def handle(msg: Any) -> Optional[Dict[str, Any]]:
    """Handle one JSON-RPC message. Returns the response, or None for notifications."""

    def err(code: int, message: str, id_=None):
        return {"jsonrpc": "2.0", "id": id_, "error": {"code": code, "message": message}}

    if not isinstance(msg, dict) or msg.get("jsonrpc") != "2.0" or not isinstance(
            msg.get("method"), str):
        return err(-32600, "Invalid Request", msg.get("id") if isinstance(msg, dict) else None)
    method, params = msg["method"], msg.get("params") or {}
    is_notification = "id" not in msg
    id_ = msg.get("id")
    if is_notification:
        return None  # notifications/initialized, notifications/cancelled, ...

    def ok(result):
        return {"jsonrpc": "2.0", "id": id_, "result": result}

    if method == "initialize":
        asked = params.get("protocolVersion") if isinstance(params, dict) else None
        version = asked if asked in PROTOCOL_VERSIONS else PROTOCOL_VERSIONS[0]
        return ok({
            "protocolVersion": version,
            "capabilities": {"tools": {"listChanged": False}},
            "serverInfo": {"name": SERVER_NAME, "version": _version()},
            "instructions": "Use check_model on a Python file defining get_model() and "
                            "get_inputs(); act on next_actions in its result. grad_check, "
                            "port_check, invariance_check, record, diff, export_model and "
                            "verify_kernel run "
                            "the other truestar checks the same way.",
        })
    if method == "ping":
        return ok({})
    if method == "tools/list":
        return ok({"tools": TOOLS})
    if method == "tools/call":
        if not isinstance(params, dict) or not isinstance(params.get("name"), str):
            return err(-32602, "tools/call needs params.name", id_)
        try:
            doc, is_error = call_tool(params["name"], params.get("arguments"))
        except UnknownTool:
            return err(-32602, f"Unknown tool: {params['name']}", id_)
        except Exception as exc:  # a tool bug must not kill the server
            doc, is_error = {"error": f"{type(exc).__name__}: {exc}"}, True
        return ok(tool_result(doc, is_error))
    return err(-32601, f"Method not found: {method}", id_)


def serve_builtin(stdin=None, stdout=None) -> int:
    stdin = stdin or sys.stdin.buffer
    stdout = stdout or sys.stdout.buffer
    for raw in stdin:
        line = raw.decode("utf-8", errors="replace").strip() if isinstance(raw, bytes) else raw.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except ValueError:
            resp = {"jsonrpc": "2.0", "id": None, "error": {"code": -32700, "message": "Parse error"}}
        else:
            resp = handle(msg)
        if resp is not None:
            stdout.write((json.dumps(resp, allow_nan=False) + "\n").encode("utf-8"))
            stdout.flush()
    return 0


