"""MCP server for AI coding agents: `truestar mcp` (stdio).

Tools:
    list_backends     the compute backends on this machine
    check_model       run `truestar check --format agent` on a model file, return the agent JSON
    run_repro         run a repro.py written by truestar check, on its backend or another device
    grad_check        `truestar check --backward`: per module backward replay against float64
    port_check        `truestar port`: does a second implementation compute the same model
    invariance_check  `truestar invariance`: does a row's result depend on the rest of the batch
    record            `truestar record`: store every module call of a model to a .tsrec file
    diff              `truestar diff`: what changed against a recording, module and op named
    export_model      `truestar export`: write a verified .tsx artifact, or refuse
    verify_kernel     `truestar kernel`: a kernel against its reference over many inputs

Two transports share the same tool code:
    sdk      the official `mcp` Python package (1.x), used when it is installed
    builtin  a dependency free JSON-RPC 2.0 server (newline delimited JSON on stdin/stdout)

Every tool runs the truestar CLI in a child process, so a crash or a print in the user's model can
never corrupt the protocol stream or take the server down. Tools that run or overwrite a file
check first that truestar wrote it: run_repro runs only repro.py scripts from truestar check, diff
reads only .tsrec recordings, record and export_model overwrite only a recording or an artifact.
"""

