def _child_env() -> Dict[str, str]:
    """Environment for child processes: this truestar package must be importable there."""
    env = dict(os.environ)
    src = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    old = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = src + (os.pathsep + old if old else "")
    env["PYTHONIOENCODING"] = "utf-8"
    return env


def _tail(s: str) -> str:
    return s if len(s) <= MAX_STREAM else "...\n" + s[-MAX_STREAM:]


def _arg(args: Dict[str, Any], name: str, typ, default=None, required=False):
    if name not in args or args[name] is None:
        if required:
            raise ToolArgumentError(f"missing required argument {name!r}")
        return default
    v = args[name]
    if typ is float and isinstance(v, int) and not isinstance(v, bool):
        v = float(v)
    if not isinstance(v, typ) or (typ is not bool and isinstance(v, bool)):
        raise ToolArgumentError(f"argument {name!r} must be {typ.__name__}")
    return v


def tool_list_backends(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    # In a child process, like the other tools: the server itself never loads torch.
    p = subprocess.run([sys.executable, "-m", "truestar", "backends"], stdin=subprocess.DEVNULL,
                       capture_output=True, text=True, encoding="utf-8", errors="replace",
                       env=_child_env(), timeout=300)
    try:
        doc = json.loads(p.stdout)
    except ValueError:
        return {"error": f"truestar backends failed: {_tail(p.stderr)}"}, True
    return doc, False


def _strings(args: Dict[str, Any], name: str) -> Optional[List[str]]:
    v = _arg(args, name, list)
    if v is not None and not all(isinstance(b, str) for b in v):
        raise ToolArgumentError(f"argument {name!r} must be a list of strings")
    return v


def _int(args: Dict[str, Any], name: str, default=None, minimum: int = 0) -> Optional[int]:
    v = _arg(args, name, int, default)
    if v is not None and v < minimum:
        raise ToolArgumentError(f"argument {name!r} must be at least {minimum}")
    return v


def _cwd(path: str) -> Optional[str]:
    d = os.path.dirname(path)
    return d if os.path.isdir(d) else None


def _run_agent(cmd: List[str], command: str, model_file: Optional[str],
               timeout: float, cwd: Optional[str]) -> Tuple[Dict[str, Any], bool]:
    """Run `python -m truestar <cmd> --format agent` in a child; return its one JSON document."""
    from .agent import error_to_agent

    def error(message: str) -> Tuple[Dict[str, Any], bool]:
        doc = error_to_agent("TS021", message, model_file)
        doc["command"] = command
        return doc, True

    try:
        p = subprocess.run([sys.executable, "-m", "truestar"] + cmd + ["--format", "agent"],
                           stdin=subprocess.DEVNULL, capture_output=True, text=True,
                           encoding="utf-8", errors="replace", env=_child_env(), timeout=timeout,
                           cwd=cwd)
    except subprocess.TimeoutExpired:
        return error(f"{command} timed out after {timeout:.0f} s")
    try:
        doc = json.loads(p.stdout)
    except ValueError:
        return error(f"truestar {command} exited {p.returncode} without agent JSON. "
                     f"stderr: {_tail(p.stderr)}")
    if p.stderr.strip():
        doc["stderr_tail"] = _tail(p.stderr)
    return doc, doc.get("exit_code") == 2


def _has_magic(path: str, magic: bytes) -> bool:
    try:
        with open(path, "rb") as f:
            return f.read(len(magic)) == magic
    except OSError:
        return False


def _output_path(path: str, magic: bytes, what: str) -> str:
    """A new output path, or an existing file truestar wrote (it starts with `magic`)."""
    path = os.path.abspath(path)
    if os.path.isdir(path):
        raise ToolArgumentError(f"{path} is a directory")
    if os.path.exists(path) and not _has_magic(path, magic):
        raise ToolArgumentError(f"{path} exists and is not a truestar {what}; refusing to "
                                f"overwrite it")
    return path


def _repro_args(args: Dict[str, Any], next_to: str) -> List[str]:
    if not _arg(args, "write_repro", bool, True):
        return ["--no-repro"]
    repro_dir = _arg(args, "repro_dir", str) or os.path.join(os.path.dirname(next_to),
                                                             "truestar_repro")
    return ["--repro-dir", os.path.abspath(repro_dir)]


def tool_check_model(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    path = os.path.abspath(_arg(args, "model_path", str, required=True))
    backends = _strings(args, "backends")
    timeout = _arg(args, "timeout_s", float, 900.0)
    cmd = ["check", path] + (["--backends", ",".join(backends)] if backends else [])
    return _run_agent(cmd + _repro_args(args, path), "check", path, timeout, _cwd(path))


def tool_grad_check(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    path = os.path.abspath(_arg(args, "model_path", str, required=True))
    backends = _strings(args, "backends")
    steps = _int(args, "steps", 0)
    lr = _arg(args, "lr", float, 1e-2)
    timeout = _arg(args, "timeout_s", float, 900.0)
    cmd = ["check", path, "--backward", "--steps", str(steps), "--lr", repr(lr)]
    cmd += ["--backends", ",".join(backends)] if backends else []
    return _run_agent(cmd + _repro_args(args, path), "check", path, timeout, _cwd(path))


def tool_port_check(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    ref = os.path.abspath(_arg(args, "reference_path", str, required=True))
    cand = os.path.abspath(_arg(args, "candidate_path", str, required=True))
    timeout = _arg(args, "timeout_s", float, 900.0)
    return _run_agent(["port", ref, cand], "port", ref, timeout, _cwd(ref))


def tool_invariance_check(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    path = os.path.abspath(_arg(args, "model_path", str, required=True))
    backends = _strings(args, "backends")
    sizes = _arg(args, "sizes", list)
    if sizes is not None and not (sizes and all(
            isinstance(n, int) and not isinstance(n, bool) and n >= 2 for n in sizes)):
        raise ToolArgumentError("argument 'sizes' must be a non empty list of integers >= 2")
    rows = _int(args, "rows", None, minimum=1)
    decode = _int(args, "decode")
    seq_pad = _int(args, "seq_pad")
    try_flags = _arg(args, "try_flags", bool, True)
    timeout = _arg(args, "timeout_s", float, 900.0)
    cmd = ["invariance", path]
    cmd += ["--backends", ",".join(backends)] if backends else []
    cmd += ["--sizes", ",".join(str(n) for n in sizes)] if sizes else []
    for flag, v in (("--rows", rows), ("--decode", decode), ("--seq-pad", seq_pad)):
        cmd += [flag, str(v)] if v is not None else []
    cmd += [] if try_flags else ["--no-flags"]
    return _run_agent(cmd, "invariance", path, timeout, _cwd(path))


def tool_record(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    path = os.path.abspath(_arg(args, "model_path", str, required=True))
    out = _output_path(_arg(args, "output_path", str, required=True), RECORD_MAGIC, "recording")
    backend = _arg(args, "backend", str)
    ops = _arg(args, "ops", str)
    outputs_only = _arg(args, "outputs_only", bool, False)
    max_mb = _arg(args, "max_mb", float)
    timeout = _arg(args, "timeout_s", float, 900.0)
    cmd = ["record", path, "-o", out]
    cmd += ["--backend", backend] if backend else []
    cmd += ["--ops", ops] if ops else []
    cmd += ["--outputs-only"] if outputs_only else []
    cmd += ["--max-mb", repr(max_mb)] if max_mb is not None else []
    return _run_agent(cmd, "record", path, timeout, _cwd(path))


def tool_diff(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    recorded = os.path.abspath(_arg(args, "recorded_path", str, required=True))
    current = _arg(args, "current_path", str)
    model = _arg(args, "model_path", str)
    backend = _arg(args, "backend", str)
    strict = _arg(args, "strict", bool, False)
    timeout = _arg(args, "timeout_s", float, 900.0)
    current = os.path.abspath(current) if current else None
    for p in [recorded] + ([current] if current else []):
        # Only recordings truestar wrote are read: a replay imports the model file they name.
        if not os.path.isfile(p):
            raise ToolArgumentError(f"{p} not found")
        if not _has_magic(p, RECORD_MAGIC):
            raise ToolArgumentError(f"{p} is not a recording written by truestar record")
    model = os.path.abspath(model) if model else None
    cmd = ["diff", recorded] + ([current] if current else ["--replay"])
    cmd += ["--model", model] if model else []
    cmd += ["--backend", backend] if backend else []
    cmd += ["--strict"] if strict else []
    return _run_agent(cmd + _repro_args(args, recorded), "diff", model, timeout, _cwd(recorded))


def _artifact_header(path: str) -> Optional[Dict[str, Any]]:
    """Header of a .tsx artifact (docs/EXPORT.md, file format), read without importing torch."""
    import struct

    try:
        with open(path, "rb") as f:
            magic, version, _, hlen = struct.unpack("<8sIIQ", f.read(24))
            if magic != ARTIFACT_MAGIC:
                return None
            header = json.loads(f.read(hlen).decode("utf-8"))
    except (OSError, ValueError, struct.error):
        return None
    return {"format_version": version, "program_hash": header.get("program_hash"),
            "evidence": (header.get("metadata") or {}).get("truestar_export")}


def tool_export_model(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    from .agent import _envelope, error_to_agent

    path = os.path.abspath(_arg(args, "model_path", str, required=True))
    out = _output_path(_arg(args, "output_path", str, required=True), ARTIFACT_MAGIC, "artifact")
    static = _arg(args, "static_batch", bool, False)
    max_batch = _int(args, "max_batch", None, minimum=1)
    second = _int(args, "second_batch", None, minimum=1)
    tol = _arg(args, "tolerance", float)
    decompose = _arg(args, "decompose", bool, False)
    timeout = _arg(args, "timeout_s", float, 900.0)
    cmd = [sys.executable, "-m", "truestar", "export", path, "-o", out]
    cmd += ["--static-batch"] if static else []
    cmd += ["--max-batch", str(max_batch)] if max_batch is not None else []
    cmd += ["--second-batch", str(second)] if second is not None else []
    cmd += ["--tolerance", repr(tol)] if tol is not None else []
    cmd += ["--decompose"] if decompose else []
    before = os.stat(out).st_mtime_ns if os.path.exists(out) else None
    try:
        p = subprocess.run(cmd, stdin=subprocess.DEVNULL, capture_output=True, text=True,
                           encoding="utf-8", errors="replace", env=_child_env(), timeout=timeout,
                           cwd=_cwd(path))
    except subprocess.TimeoutExpired:
        doc = error_to_agent("TS021", f"export timed out after {timeout:.0f} s", path)
        doc["command"] = "export"
        return doc, True
    # truestar export exit codes: 0 written, 1 refused (nothing written), 2 usage error.
    status = {0: "written", 1: "refused"}.get(p.returncode, "error")
    if status == "error":
        doc = error_to_agent("TS021", f"truestar export exited {p.returncode}: "
                                      f"{_tail(p.stderr).strip()}", path)
    else:
        doc = _envelope(status, p.returncode)
        doc.update({"model": {"file": path}, "codes": [], "issues": [], "next_actions": []})
    doc.update({"command": "export", "artifact": None, "stdout": _tail(p.stdout),
                "stderr": _tail(p.stderr)})
    if status == "written":
        header = _artifact_header(out)
        if header is None or (before is not None and os.stat(out).st_mtime_ns == before):
            err = error_to_agent("TS021", f"truestar export exited 0 but no new artifact is at "
                                          f"{out}", path)
            err.update({"command": "export", "artifact": None, "stdout": doc["stdout"],
                        "stderr": doc["stderr"]})
            return err, True
        doc["artifact"] = dict(path=out, bytes=os.path.getsize(out), **header)
        doc["next_actions"] = [{
            "kind": "run_artifact",
            "description": "Run the artifact without the model code; inputs.pt holds a tensor "
                           "or a list of tensors.",
            "command": f'truestar run "{out}" inputs.pt -o outputs.pt'}]
    elif status == "refused":
        doc["next_actions"] = [{
            "kind": "fix_export",
            "description": "Nothing was written. stderr names the failed check or the line "
                           "that cannot be exported, and the fix to try.",
            "command": None}]
    return doc, status == "error"


def tool_run_repro(args: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    path = os.path.abspath(_arg(args, "repro_path", str, required=True))
    device = _arg(args, "device", str)
    timeout = _arg(args, "timeout_s", float, 300.0)
    if os.path.basename(path) != "repro.py" or not os.path.isfile(path):
        raise ToolArgumentError(f"{path} is not a repro.py file")
    with open(path, encoding="utf-8", errors="replace") as f:
        head = f.read(400)
    if REPRO_MARKER not in head:
        # Only scripts truestar wrote are run, so this tool cannot be used to run arbitrary code.
        raise ToolArgumentError(f"{path} was not written by truestar check")
    cmd = [sys.executable, path] + ([device] if device else [])
    try:
        p = subprocess.run(cmd, stdin=subprocess.DEVNULL, capture_output=True, text=True, encoding="utf-8",
                           errors="replace", env=_child_env(), timeout=timeout,
                           cwd=os.path.dirname(path))
    except subprocess.TimeoutExpired:
        return {"repro_path": path, "device": device, "exit_code": None, "reproduced": None,
                "error": f"timed out after {timeout:.0f} s"}, True
    reproduced = p.returncode == 1 and "REPRODUCED" in p.stdout
    passed = p.returncode == 0
    doc = {
        "repro_path": path,
        "device": device,
        "command": " ".join(f'"{c}"' if " " in c else c for c in cmd),
        "exit_code": p.returncode,
        "reproduced": reproduced,
        "passed": passed,
        "stdout": _tail(p.stdout),
        "stderr": _tail(p.stderr),
    }
    return doc, not (reproduced or passed)  # anything else is a crash of the repro itself


