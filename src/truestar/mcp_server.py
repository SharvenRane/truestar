def _sdk_api(server) -> Optional[str]:
    """Which server API the installed official SDK has: "1.x" (the list_tools() and call_tool()
    decorators), "2.x" (handlers as on_list_tools= and on_call_tool= constructor arguments), or None."""
    if hasattr(server, "list_tools") and hasattr(server, "call_tool"):
        return "1.x"
    try:
        params = inspect.signature(server.__init__).parameters
    except (TypeError, ValueError):
        return None
    if "on_list_tools" in params and "on_call_tool" in params:
        return "2.x"
    return None


def sdk_problem() -> Optional[str]:
    """None when the official SDK's server API (1.x or 2.x) is importable, else why the sdk
    transport can't run."""
    try:
        import mcp.server.lowlevel
        import mcp.server.stdio  # noqa: F401
    except Exception:
        return "the mcp package is not installed"
    if _sdk_api(mcp.server.lowlevel.Server) is None:
        try:
            from importlib.metadata import version
            found = f"mcp {version('mcp')} is installed"
        except Exception:
            found = "the installed mcp package"
        return (f"{found} but has neither the 1.x Server decorators nor the 2.x on_list_tools/"
                f"on_call_tool handlers; the sdk transport needs mcp 1.10 or later")
    return None


def sdk_available() -> bool:
    return sdk_problem() is None


def _sdk_tools(types) -> list:
    return [types.Tool(name=t["name"], title=t.get("title"), description=t["description"],
                       inputSchema=t["inputSchema"]) for t in TOOLS]


async def _sdk_call(types, name: str, arguments: Optional[Dict[str, Any]]):
    """One tools/call for either SDK: the same validation and errors as the builtin server, run in
    a worker thread; an unknown tool is a tool error result."""
    import anyio

    if name not in _TOOL_NAMES:
        doc, is_error = {"error": f"Unknown tool: {name}"}, True
    else:
        doc, is_error = await anyio.to_thread.run_sync(call_tool, name, arguments)
    return types.CallToolResult(
        content=[types.TextContent(type="text", text=json.dumps(doc, indent=2, allow_nan=False))],
        structuredContent=doc,
        isError=bool(is_error),
    )


def serve_sdk() -> int:
    import anyio
    import mcp.types as types
    from mcp.server.lowlevel import NotificationOptions, Server
    from mcp.server.stdio import stdio_server

    if _sdk_api(Server) == "2.x":
        async def _list_tools2(ctx, params):
            return types.ListToolsResult(tools=_sdk_tools(types))

        async def _call_tool2(ctx, params):
            return await _sdk_call(types, params.name, params.arguments)

        server = Server(SERVER_NAME, version=_version(),
                        on_list_tools=_list_tools2, on_call_tool=_call_tool2)

        def options():
            return server.create_initialization_options(NotificationOptions())
    else:
        from mcp.server.models import InitializationOptions

        server = Server(SERVER_NAME)

        @server.list_tools()
        async def _list_tools() -> List[types.Tool]:
            return _sdk_tools(types)

        @server.call_tool(validate_input=False)  # call_tool validates, with the same errors as builtin
        async def _call_tool(name: str, arguments: Dict[str, Any]):
            return await _sdk_call(types, name, arguments)

        def options():
            return InitializationOptions(
                server_name=SERVER_NAME,
                server_version=_version(),
                capabilities=server.get_capabilities(NotificationOptions(), {}),
            )

    async def run() -> None:
        async with stdio_server() as (read, write):
            await server.run(read, write, options())

    anyio.run(run)
    return 0


def serve(impl: str = "auto") -> int:
    problem = sdk_problem() if impl in ("auto", "sdk") else None
    if impl == "sdk" and problem:
        print(f"truestar mcp: {problem}; use --impl builtin", file=sys.stderr)
        return 2
    if impl == "sdk" or (impl == "auto" and problem is None):
        return serve_sdk()
    return serve_builtin()
