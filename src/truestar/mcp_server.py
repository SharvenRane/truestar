def call_tool(name: str, args: Optional[Dict[str, Any]]) -> Tuple[Dict[str, Any], bool]:
    """Run one tool. Returns (structured result, is_error). Raises UnknownTool."""
    if name not in _HANDLERS:
        raise UnknownTool(name)
    if args is not None and not isinstance(args, dict):
        return {"error": "arguments must be an object"}, True
    args = args or {}
    allowed = set(next(t for t in TOOLS if t["name"] == name)["inputSchema"]["properties"])
    extra = sorted(set(args) - allowed)
    if extra:
        return {"error": f"unknown argument(s) {extra} for {name}"}, True
    try:
        return _HANDLERS[name](args)
    except ToolArgumentError as exc:
        return {"error": str(exc)}, True


def tool_result(doc: Dict[str, Any], is_error: bool) -> Dict[str, Any]:
    return {
        "content": [{"type": "text", "text": json.dumps(doc, indent=2, allow_nan=False)}],
        "structuredContent": doc,
        "isError": bool(is_error),
    }


