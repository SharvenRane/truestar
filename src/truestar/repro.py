"""Write a standalone repro for one divergent layer. The script needs only PyTorch."""

from __future__ import annotations

import copy
import os
import re
import sys
from typing import Optional

import torch
from torch import nn

from .backends import Backend
from .capture import Call

SCRIPT = '''"""Repro generated by truestar check.

Layer:    {layer} ({type_name}) from model {model}
Backend:  {backend} ({description})
Expected: relative error below {threshold:.1e} versus a float64 CPU reference.

Run:  python repro.py            (uses the backend above)
      python repro.py cpu        (control run, should pass)
Needs only PyTorch. If the layer is a custom class, its module must be importable.
{sim_note}Exit code 1 means the divergence reproduced.
"""
import contextlib
import os
import sys

import torch

HERE = os.path.dirname(os.path.abspath(__file__))
# Folders holding the source of custom module classes, so the payload can be unpickled.
for _p in {import_paths!r}:
    if os.path.isdir(_p) and _p not in sys.path:
        sys.path.append(_p)
DTYPE = {dtype}
THRESHOLD = {threshold!r}


def tensors(o):
    if isinstance(o, torch.Tensor):
        return [o]
    if isinstance(o, (list, tuple)):
        return [t for x in o for t in tensors(x)]
    if isinstance(o, dict):
        return [t for k in sorted(o, key=str) for t in tensors(o[k])]
    return []


def move(o, device):
    if isinstance(o, torch.Tensor):
        return o.to(device=device, dtype=DTYPE) if o.is_floating_point() else o.to(device)
    if isinstance(o, tuple):
        return tuple(move(x, device) for x in o)
    if isinstance(o, list):
        return [move(x, device) for x in o]
    if isinstance(o, dict):
        return {{k: move(v, device) for k, v in o.items()}}
    return o


def rel_err(a, b):
    a, b = a.detach().cpu().double(), b.detach().cpu().double()
    if not torch.equal(torch.isfinite(a), torch.isfinite(b)):
        return float("inf")
    m = torch.isfinite(b)
    num = torch.linalg.vector_norm((a - b)[m]).item()
    den = torch.linalg.vector_norm(b[m]).item()
    return 0.0 if num == 0 else (num / den if den else float("inf"))


def main():
    device = sys.argv[1] if len(sys.argv) > 1 else {device!r}
{sim_main}    p = torch.load(os.path.join(HERE, "payload.pt"), weights_only=False)
    module = p["module"].to(device).eval()
    with torch.no_grad(), ctx:
        out = module(*move(p["args"], device), **move(p["kwargs"], device))
    errs = [rel_err(a, b) for a, b in zip(tensors(out), p["reference"])]
    worst = max(errs) if errs else 0.0
    print(f"torch {{torch.__version__}} on {{shown}}: relative error {{worst:.3e}} (threshold {{THRESHOLD:.1e}})")
    if worst > THRESHOLD:
        print("REPRODUCED: output diverges from the float64 CPU reference")
        sys.exit(1)
    print("ok: output matches the reference")


if __name__ == "__main__":
    main()
'''


def _slug(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", s)[:80]


def write_repro(repro_dir: str, model_name: str, backend: Backend, call: Call,
                module: nn.Module, dtype: torch.dtype, threshold: float) -> str:
    out_dir = os.path.join(repro_dir, _slug(f"{backend.name}_{call.key}"))
    os.makedirs(out_dir, exist_ok=True)
    mod = copy.deepcopy(module).cpu().to(dtype).eval()
    payload = {
        "module": mod,
        "args": call.args,
        "kwargs": call.kwargs,
        "reference": [t.double() if t.is_floating_point() else t for t in call.outputs],
    }
    torch.save(payload, os.path.join(out_dir, "payload.pt"))
    import_paths = []
    for m in mod.modules():
        f = getattr(sys.modules.get(type(m).__module__), "__file__", None)
        top = type(m).__module__.split(".")[0]
        if f and top not in ("torch", "truestar", "torchvision"):
            d = os.path.dirname(os.path.abspath(f))
            for _ in range(type(m).__module__.count(".")):
                d = os.path.dirname(d)  # package modules: the folder above the package
            if d not in import_paths:
                import_paths.append(d)
    script = SCRIPT.format(
        layer=call.key,
        type_name=call.type_name,
        model=model_name,
        backend=backend.name,
        description=backend.description,
        threshold=threshold,
        dtype="torch." + str(dtype).replace("torch.", ""),
        device=backend.sim or backend.device,
        **_sim_parts(backend),
        import_paths=import_paths,
    )
    path = os.path.join(out_dir, "repro.py")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(script)
    return path



def _sim_parts(backend: Backend) -> dict:
    """Lines only a simulated backend's repro needs; a real backend's repro stays PyTorch only."""
    if getattr(backend, "sim", None):
        return {
            "sim_note": "A simulated backend (sim:...) needs truestar installed: it replays the simulation on the CPU.\n",
            "sim_main": ("    ctx, shown = contextlib.nullcontext(), device\n"
                         "    if device.startswith(\"sim:\"):\n"
                         "        from truestar.devsim import simulate\n\n"
                         "        ctx, device, shown = simulate(device), \"cpu\", device\n"),
            "sim_op": ("ctx, shown = contextlib.nullcontext(), dev\n"
                       "if dev.startswith(\"sim:\"):  # a simulated backend: needs truestar, replays on the CPU\n"
                       "    from truestar.devsim import simulate\n"
                       "    ctx, dev, shown = simulate(dev), \"cpu\", dev\n"),
        }
    return {"sim_note": "",
            "sim_main": "    ctx, shown = contextlib.nullcontext(), device\n",
            "sim_op": "ctx, shown = contextlib.nullcontext(), dev\n"}

