def write_op_repro(repro_dir: str, model_name: str, backend: Backend, call: Call, op) -> str:
    """Write op_repro.py calling the single ATen op `op` (an OpResult) with its saved tensors."""
    out_dir = os.path.join(repro_dir, _slug(f"{backend.name}_{call.key}"))
    os.makedirs(out_dir, exist_ok=True)
    payload = {"op": op.op, "args": op.args, "kwargs": op.kwargs,
               "reference": [t.double() if t.is_floating_point() else t for t in op.reference]}
    torch.save(payload, os.path.join(out_dir, "op_payload.pt"))
    inputs = ", ".join(f"{d}{s}" for d, s in zip(op.input_dtypes, op.input_shapes)) or "none"
    script = OP_SCRIPT.format(op=op.op, backend=backend.name, description=backend.description,
                              layer=call.key, model=model_name, inputs=inputs,
                              threshold=op.threshold, device=backend.sim or backend.device,
                              **_sim_parts(backend))
    path = os.path.join(out_dir, "op_repro.py")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(script)
    return path
