"""Standalone repros for compiler and runtime backends (truestar.stacks).

The script runs one module, or one ATen op, through the same stack the check used and compares it
with the saved float64 answer. `python repro.py eager` is the control. Test hooks set through
stack options (an injected fault) are not carried into the script.
"""

from __future__ import annotations

import copy
import os
import sys

import torch
from torch import nn

from .backends import Backend
from .capture import Call
from .repro import _slug

STACK_SCRIPT = '''"""Repro generated by truestar check for a compiler or runtime backend.

What:     {what} from model {model}
Backend:  {backend} ({description})
Expected: relative error below {threshold:.1e} versus a float64 CPU reference.

Run:  python {fname}           (through {backend})
      python {fname} eager     (control: eager PyTorch on CPU, should pass; "cpu" also works)
Needs PyTorch plus {needs}. Exit code 1 means the divergence reproduced.
"""
import os
import sys

import torch

HERE = os.path.dirname(os.path.abspath(__file__))
for _p in {import_paths!r}:
    if os.path.isdir(_p) and _p not in sys.path:
        sys.path.append(_p)
STACK = {backend!r}
THRESHOLD = {threshold!r}


def leaves(o):
    if isinstance(o, torch.Tensor):
        return [o]
    if isinstance(o, (list, tuple)):
        return [t for x in o for t in leaves(x)]
    if isinstance(o, dict):
        return [t for v in o.values() for t in leaves(v)]
    return []


class OpCall(torch.nn.Module):
    """One ATen op whose tensor arguments are the module inputs."""

    def __init__(self, op, args, kwargs):
        super().__init__()
        from torch.utils import _pytree as pytree
        flat, self.spec = pytree.tree_flatten((args, kwargs))
        self.slots = [i for i, x in enumerate(flat) if isinstance(x, torch.Tensor)]
        self.consts = [None if isinstance(x, torch.Tensor) else x for x in flat]
        self.op = op

    def forward(self, *ts):
        from torch.utils import _pytree as pytree
        flat = list(self.consts)
        for i, t in zip(self.slots, ts):
            flat[i] = t
        a, k = pytree.tree_unflatten(flat, self.spec)
        return self.op(*a, **k)


def to(o, device):
    if isinstance(o, torch.Tensor):
        return o.to(device)
    if isinstance(o, (list, tuple)):
        return type(o)(to(x, device) for x in o)
    if isinstance(o, dict):
        return {{k: to(v, device) for k, v in o.items()}}
    return o


def run(stack, module, args, kwargs):
    if stack in ("eager", "cpu"):
        return leaves(module(*args, **kwargs))
    if stack.endswith("+inductor"):
        dev = "cuda" if stack.startswith("cuda") else "cpu"
        out = torch.compile(module.to(dev), backend="inductor")(*to(args, dev), **to(kwargs, dev))
        return [t.cpu() for t in leaves(out)]
    proto = torch.onnx.export(module, tuple(args), kwargs=kwargs or None, dynamo=True,
                              verbose=False).model_proto
    init = {{i.name for i in proto.graph.initializer}}
    names = [i.name for i in proto.graph.input if i.name not in init]
    feeds = leaves((args, kwargs))
    if stack.startswith("ort:"):
        import onnxruntime as ort
        provs = (["CUDAExecutionProvider", "CPUExecutionProvider"] if stack == "ort:cuda"
                 else ["CPUExecutionProvider"])
        s = ort.InferenceSession(proto.SerializeToString(), providers=provs)
        outs = s.run(None, {{n: t.contiguous().numpy() for n, t in zip(names, feeds)}})
        return [torch.from_numpy(o) for o in outs]
    import tensorrt as trt
    log = trt.Logger(trt.Logger.ERROR)
    b = trt.Builder(log)
    net = b.create_network(0)
    parser = trt.OnnxParser(net, log)
    assert parser.parse(proto.SerializeToString()), "TensorRT could not parse the model"
    cfg = b.create_builder_config()
    if stack != "trt:tf32":
        cfg.clear_flag(trt.BuilderFlag.TF32)
    if stack == "trt:fp16":
        cfg.set_flag(trt.BuilderFlag.FP16)
    eng = trt.Runtime(log).deserialize_cuda_engine(b.build_serialized_network(net, cfg))
    ctx = eng.create_execution_context()
    types = {{trt.float32: torch.float32, trt.float16: torch.float16, trt.int32: torch.int32,
             trt.int64: torch.int64, trt.bool: torch.bool}}
    keep = []
    for n, t in zip(names, feeds):
        d = t.to("cuda", types[eng.get_tensor_dtype(n)]).contiguous()
        keep.append(d)
        ctx.set_input_shape(n, tuple(d.shape))
        ctx.set_tensor_address(n, d.data_ptr())
    outs = []
    for o in proto.graph.output:
        x = torch.empty(tuple(ctx.get_tensor_shape(o.name)),
                        dtype=types[eng.get_tensor_dtype(o.name)], device="cuda")
        outs.append(x)
        ctx.set_tensor_address(o.name, x.data_ptr())
    ctx.execute_async_v3(torch.cuda.current_stream().cuda_stream)
    torch.cuda.synchronize()
    return [x.cpu() for x in outs]


def rel_err(a, b):
    a, b = a.detach().cpu().double(), b.detach().cpu().double()
    if a.shape != b.shape or not torch.equal(torch.isfinite(a), torch.isfinite(b)):
        return float("inf")
    m = torch.isfinite(b)
    num = torch.linalg.vector_norm((a - b)[m]).item()
    den = torch.linalg.vector_norm(b[m]).item()
    return 0.0 if num == 0 else (num / den if den else float("inf"))


def main():
    stack = sys.argv[1] if len(sys.argv) > 1 else STACK
    p = torch.load(os.path.join(HERE, {payload!r}), weights_only=False)
    if "op" in p:
        ns, packet, overload = p["op"].split(".")
        func = getattr(getattr(getattr(torch.ops, ns), packet), overload)
        module = OpCall(func, p["args"], p["kwargs"])
        args, kwargs = tuple(leaves((p["args"], p["kwargs"]))), {{}}
    else:
        module, args, kwargs = p["module"].eval(), p["args"], p["kwargs"]
    with torch.no_grad():
        outs = run(stack, module, args, kwargs)
    errs = [rel_err(a, b) for a, b in zip(outs, p["reference"])]
    worst = max(errs) if errs else 0.0
    print(f"torch {{torch.__version__}} via {{stack}}: relative error {{worst:.3e}} "
          f"(threshold {{THRESHOLD:.1e}})")
    if worst > THRESHOLD:
        print("REPRODUCED: output diverges from the float64 CPU reference")
        sys.exit(1)
    print("ok: output matches the reference")


if __name__ == "__main__":
    main()
'''

_NEEDS = {"inductor": "triton (CUDA) or a C++ compiler (CPU)",
          "ort": "onnx, onnxscript and onnxruntime", "trt": "onnx, onnxscript and tensorrt"}


def _import_paths(mod: nn.Module):
    paths = []
    for m in mod.modules():
        f = getattr(sys.modules.get(type(m).__module__), "__file__", None)
        top = type(m).__module__.split(".")[0]
        if f and top not in ("torch", "truestar", "torchvision"):
            d = os.path.dirname(os.path.abspath(f))
            for _ in range(type(m).__module__.count(".")):
                d = os.path.dirname(d)
            if d not in paths:
                paths.append(d)
    return paths


def _write(out_dir, fname, payload_name, payload, what, model_name, backend, threshold,
           import_paths) -> str:
    os.makedirs(out_dir, exist_ok=True)
    torch.save(payload, os.path.join(out_dir, payload_name))
    script = STACK_SCRIPT.format(what=what, model=model_name, backend=backend.name,
                                 description=backend.description, threshold=threshold,
                                 fname=fname, needs=_NEEDS.get(getattr(backend, "kind", ""), ""),
                                 import_paths=import_paths, payload=payload_name)
    path = os.path.join(out_dir, fname)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(script)
    return path


def _ref(ts):
    return [t.double() if t.is_floating_point() else t for t in ts]


def write_stack_repro(repro_dir: str, model_name: str, backend: Backend, call: Call,
                      module: nn.Module, dtype: torch.dtype, threshold: float) -> str:
    """repro.py running one module through a compiler or runtime stack."""
    from .check import _cast_inputs

    mod = copy.deepcopy(module).cpu().to(dtype).eval()
    payload = {"module": mod, "args": _cast_inputs(call.args, "cpu", dtype),
               "kwargs": _cast_inputs(call.kwargs, "cpu", dtype), "reference": _ref(call.outputs)}
    return _write(os.path.join(repro_dir, _slug(f"{backend.name}_{call.key}")), "repro.py",
                  "payload.pt", payload, f"module {call.key} ({call.type_name})", model_name,
                  backend, threshold, _import_paths(mod))


def write_stack_op_repro(repro_dir: str, model_name: str, backend: Backend, call: Call,
                         op) -> str:
    """op_repro.py running one ATen op alone through a compiler or runtime stack."""
    payload = {"op": op.op, "args": op.args, "kwargs": op.kwargs, "reference": _ref(op.reference)}
    return _write(os.path.join(repro_dir, _slug(f"{backend.name}_{call.key}")), "op_repro.py",
                  "op_payload.pt", payload, f"op {op.op} in module {call.key}", model_name,
                  backend, op.threshold, [])
